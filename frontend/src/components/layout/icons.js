/**
 * Icons.
 *
 * A separate module for two reasons:
 *
 *  1. **Server components cannot import from a `'use client'` module.** The
 *     navigation has to be a Client Component because it owns the mobile menu
 *     and the language switcher's route change, but the footer and the homepage
 *     are Server Components that want the same icons and the same link list.
 *     Keeping the icons and the data here lets all three share one definition
 *     without dragging the client boundary across the whole layout.
 *  2. Every icon is `aria-hidden` and sized by its caller, so none of them
 *     carries a label. That is intentional: an icon beside a text label that is
 *     also read aloud produces a duplicate announcement, and an icon *instead*
 *     of a label conveys nothing to a screen reader.
 */

